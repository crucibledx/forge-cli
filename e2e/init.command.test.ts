/**
 * E2E tests for `forge init`.
 *
 * Strategy: spawn the CLI in a real PTY (Bun.spawn `terminal` option) so that
 * @clack/prompts enters raw mode. Use waitForText() before each input to wait
 * for the prompt to render — fully deterministic, no fixed sleeps.
 */

import {existsSync} from 'node:fs'
import {mkdir} from 'node:fs/promises'
import {join} from 'node:path'

import {beforeEach, describe, expect, it} from 'bun:test'
import {map} from 'lodash-es'

import {claudeCode} from '@domain/assistants/claude-code'
import {cline} from '@domain/assistants/cline'
import {copilot} from '@domain/assistants/copilot'
import {cursor} from '@domain/assistants/cursor'
import {windsurf} from '@domain/assistants/windsurf'
import type {GitSource} from '@domain/config/types'

import type {CliStep} from './helpers'
import {
    ARROW_DOWN,
    type CLISession,
    CONFIG_FILE,
    configFilePath,
    crucibleDirPath,
    CTRL_C,
    INIT_MESSAGES as M,
    N,
    readConfig,
    readConfigRaw,
    runInitSession,
    spawnCommand,
    TIMEOUT_MS,
    useTmpDir,
    Y,
} from './helpers'

// ─── Temp directory ───────────────────────────────────────────────────────────

const getDir = useTmpDir('forge-e2e')

// ─── Reusable drivers ─────────────────────────────────────────────────────────

function declineAllAssistants(cli: CLISession): CliStep {
    return cli
        .waitForText(M.assistants.addUndetected(claudeCode.name)).pressKey(N)
        .waitForText(M.assistants.addUndetected(cursor.name)).pressKey(N)
        .waitForText(M.assistants.addUndetected(windsurf.name)).pressKey(N)
        .waitForText(M.assistants.addUndetected(copilot.name)).pressKey(N)
        .waitForText(M.assistants.addUndetected(cline.name)).pressKey(N)
}

function declineAll(cli: CLISession): CliStep {
    return declineAllAssistants(cli)
        // then decline adding a source
        .waitForText(M.source.addSource).pressKey(N)
}

const SOURCE_URL = 'git@github.com:org/ai-configs.git'

function addSource(cli: CLISession): CliStep {
    return declineAllAssistants(cli)
        // then accept adding a source
        .waitForText(M.source.addSource).pressKey(Y)
        // select source type — press Enter to pick the first option (git)
        .waitForText(M.source.selectType).pressEnter()
        // write source URL
        .waitForText(M.source.git.url.message).write(SOURCE_URL).pressEnter()
        // skip branch - use default
        .waitForText(M.source.git.branch).pressEnter()
        // skip subdirectory - use root
        .waitForText(M.source.git.subdirectory.message).pressEnter()
        // decline run sync command
        .waitForText(M.sync.runNow).pressKey(N)
}

// ─── Tests ────────────────────────────────────────────────────────────────────

describe('forge init — e2e', () => {
    describe('cancellation', () => {
        it('cancels gracefully on Ctrl+C — no config written', async () => {
            const cli = spawnCommand(getDir(), 'init')
            const done = cli.waitForExit()
            await cli.waitForText(M.assistants.addUndetected('Claude Code')).pressKey(CTRL_C)
            const {exitCode} = await done
            expect([0, 1]).toContain(exitCode)
            expect(existsSync(configFilePath(getDir()))).toBe(false)
        }, TIMEOUT_MS)
    })

    describe('minimal config (all declined)', () => {
        it('writes a valid config file', async () => {
            await runInitSession(getDir(), declineAll)
            expect(existsSync(configFilePath(getDir()))).toBe(true)

            const config = await readConfig(getDir())
            expect(config.version).toBeDefined()
            expect(Array.isArray(config.assistants)).toBe(true)
            expect(config.assistants).toHaveLength(0)
            expect(config.source).toBeUndefined()
            expect(config.project?.name).toBe(getDir().split('/').at(-1))
        }, TIMEOUT_MS)

        it('file contains forge header comment', async () => {
            await runInitSession(getDir(), declineAll)
            expect(existsSync(configFilePath(getDir()))).toBe(true)

            const raw = await readConfigRaw(getDir())
            expect(raw).toContain('# .crucible/forge.config.yaml')
            expect(raw).toContain('Generated by forge init')
        }, TIMEOUT_MS)
    })

    describe('assistant selection', () => {
        it('enables a single selected assistant (Cursor)', async () => {
            await runInitSession(getDir(), (cli) =>
                // only `cursor` is gonna be selected
                cli
                    .waitForText(M.assistants.addUndetected(claudeCode.name)).pressKey(N)
                    .waitForText(M.assistants.addUndetected(cursor.name)).pressKey(Y)
                    .waitForText(M.assistants.addUndetected(windsurf.name)).pressKey(N)
                    .waitForText(M.assistants.addUndetected(copilot.name)).pressKey(N)
                    .waitForText(M.assistants.addUndetected(cline.name)).pressKey(N)
                    .waitForText(M.source.addSource).pressKey(N),
            )

            const config = await readConfig(getDir())
            expect(config.assistants).toHaveLength(1)
            expect(config.assistants[0].id).toBe(cursor.id)
            expect(config.assistants[0].enabled).toBe(true)
        }, TIMEOUT_MS)

        it('enables multiple selected assistants', async () => {
            await runInitSession(getDir(), (cli) =>
                //  `claudeCode` and `cursor` are gonna be selected
                cli
                    .waitForText(M.assistants.addUndetected(claudeCode.name)).pressKey(Y)
                    .waitForText(M.assistants.addUndetected(cursor.name)).pressKey(Y)
                    .waitForText(M.assistants.addUndetected(windsurf.name)).pressKey(N)
                    .waitForText(M.assistants.addUndetected(copilot.name)).pressKey(N)
                    .waitForText(M.assistants.addUndetected(cline.name)).pressKey(N)
                    .waitForText(M.source.addSource).pressKey(N),
            )
            const config = await readConfig(getDir())
            expect(config.assistants).toHaveLength(2)

            const ids = map(config.assistants, a => a.id)
            expect(ids).toContainValues([claudeCode.id, cursor.id])
        }, TIMEOUT_MS)

        it('enables all assistants when all accepted', async () => {
            await runInitSession(getDir(), (cli) =>
                cli
                    .waitForText(M.assistants.addUndetected(claudeCode.name)).pressKey(Y)
                    .waitForText(M.assistants.addUndetected(cursor.name)).pressKey(Y)
                    .waitForText(M.assistants.addUndetected(windsurf.name)).pressKey(Y)
                    .waitForText(M.assistants.addUndetected(copilot.name)).pressKey(Y)
                    .waitForText(M.assistants.addUndetected(cline.name)).pressKey(Y)
                    .waitForText(M.source.addSource).pressKey(N),
            )
            const config = await readConfig(getDir())
            expect(config.assistants).toHaveLength(5)

            const ids = map(config.assistants, a => a.id)
            expect(ids).toContainValues([claudeCode.id, cursor.id, windsurf.id, copilot.id, cline.id])
        }, TIMEOUT_MS)
    })

    describe('source configuration — git', () => {
        it('writes git source with correct url, branch, name and type', async () => {
            await runInitSession(getDir(), addSource)
            expect(existsSync(configFilePath(getDir()))).toBe(true)

            const source = (await readConfig(getDir())).source as GitSource
            expect(source.type).toBe('git')
            expect(source.url).toBe(SOURCE_URL)
            expect(source.branch).toBe('main')
            expect(source.name).toBe('team-shared')
        }, TIMEOUT_MS)
    })

    describe('source configuration — local', () => {
        it('writes local source with correct path, name and type', async () => {
            const localPath = getDir()
            await runInitSession(getDir(), (cli) =>
                declineAllAssistants(cli)
                    .waitForText(M.source.addSource).pressKey(Y)
                    // arrow down to select 'Local directory' (second option)
                    .waitForText(M.source.selectType).pressKey(ARROW_DOWN).pressEnter()
                    .waitForText(M.source.local.path.message).write(localPath).pressEnter()
                    .waitForText(M.sync.runNow).pressKey(N),
            )
            const config = await readConfig(getDir())
            expect(config.source?.type).toBe('local')
            expect((config.source as {path: string}).path).toBe(localPath)
            expect(config.source?.name).toBe('team-shared')
        }, TIMEOUT_MS)
    })

    describe('existing config — aborts early', () => {
        const existingContent = '# .crucible/forge.config.yaml\nversion: "1"\nassistants: []\n'

        beforeEach(async () => {
            await Bun.write(join(crucibleDirPath(getDir()), CONFIG_FILE), existingContent)
        })

        it('exits without writing when config already exists', async () => {
            const cli = spawnCommand(getDir(), 'init')
            const done = cli.waitForExit()
            await cli.waitForText(M.configExists)
            await done
            const raw = await readConfigRaw(getDir())
            expect(raw).toEqual(existingContent)
        }, TIMEOUT_MS)

        it('does not prompt for assistants or source when config exists', async () => {
            const cli = spawnCommand(getDir(), 'init')
            const done = cli.waitForExit()
            // Should see the abort message but NOT the assistant prompt
            await cli.waitForText(M.configExists)
            const {output} = await done
            expect(output).not.toContain(M.assistants.addUndetected('Cursor'))
            expect(output).not.toContain(M.source.addSource)
        }, TIMEOUT_MS)
    })

    describe('source configuration — advanced', () => {
        it('writes custom branch when user enters one', async () => {
            await runInitSession(getDir(), (cli) =>
                declineAllAssistants(cli)
                    .waitForText(M.source.addSource).pressKey(Y)
                    .waitForText(M.source.selectType).pressEnter()
                    .waitForText(M.source.git.url.message).write(SOURCE_URL).pressEnter()
                    .waitForText(M.source.git.branch).write('develop').pressEnter()
                    .waitForText(M.source.git.subdirectory.message).pressEnter()
                    .waitForText(M.sync.runNow).pressKey(N),
            )
            const source = (await readConfig(getDir())).source as GitSource
            expect(source.branch).toBe('develop')
        }, TIMEOUT_MS)

        it('writes subdirectory path when user enters one', async () => {
            await runInitSession(getDir(), (cli) =>
                declineAllAssistants(cli)
                    .waitForText(M.source.addSource).pressKey(Y)
                    .waitForText(M.source.selectType).pressEnter()
                    .waitForText(M.source.git.url.message).write(SOURCE_URL).pressEnter()
                    .waitForText(M.source.git.branch).pressEnter()
                    .waitForText(M.source.git.subdirectory.message).write('packages/ai').pressEnter()
                    .waitForText(M.sync.runNow).pressKey(N),
            )
            const source = (await readConfig(getDir())).source as GitSource
            expect(source.path).toBe('packages/ai')
        }, TIMEOUT_MS)

        it('shows url validation error on empty input and re-prompts', async () => {
            await runInitSession(getDir(), (cli) =>
                declineAllAssistants(cli)
                    .waitForText(M.source.addSource).pressKey(Y)
                    .waitForText(M.source.selectType).pressEnter()
                    // submit empty URL — should trigger validation error
                    .waitForText(M.source.git.url.message).pressEnter()
                    // wait for the error message to appear, then enter valid URL
                    .waitForText(M.source.git.url.required).write(SOURCE_URL).pressEnter()
                    .waitForText(M.source.git.branch).pressEnter()
                    .waitForText(M.source.git.subdirectory.message).pressEnter()
                    .waitForText(M.sync.runNow).pressKey(N),
            )
            const source = (await readConfig(getDir())).source as GitSource
            expect(source.url).toBe(SOURCE_URL)
        }, TIMEOUT_MS)

        it('reaches sync-now prompt and config is written before sync attempt', async () => {
            // Accepting sync-now with a non-cloneable URL will cause sync to fail,
            // but the config MUST already be written before sync is attempted.
            const cli = spawnCommand(getDir(), 'init')
            const done = cli.waitForExit()
            await declineAllAssistants(cli)
                .waitForText(M.source.addSource).pressKey(Y)
                .waitForText(M.source.selectType).pressEnter()
                .waitForText(M.source.git.url.message).write(SOURCE_URL).pressEnter()
                .waitForText(M.source.git.branch).pressEnter()
                .waitForText(M.source.git.subdirectory.message).pressEnter()
                // accept sync — will fail because SOURCE_URL is not a real remote
                .waitForText(M.sync.runNow).pressKey(Y)
            await done
            // config was written before sync was attempted
            expect(existsSync(configFilePath(getDir()))).toBe(true)
            const source = (await readConfig(getDir())).source as GitSource
            expect(source.url).toBe(SOURCE_URL)
        }, TIMEOUT_MS)
    })

    describe('detected assistants', () => {
        it('shows keepDetected prompt when assistant config dir is present', async () => {
            // Pre-create .cursor dir so the scanner detects cursor as present
            await mkdir(join(getDir(), '.cursor'), {recursive: true})

            await runInitSession(getDir(), (cli) =>
                // claude-code is undetected → addUndetected; cursor is detected → keepDetected
                cli
                    .waitForText(M.assistants.addUndetected(claudeCode.name)).pressKey(N)
                    .waitForText(M.assistants.keepDetected(cursor.name)).pressKey(Y)
                    .waitForText(M.assistants.addUndetected(windsurf.name)).pressKey(N)
                    .waitForText(M.assistants.addUndetected(copilot.name)).pressKey(N)
                    .waitForText(M.assistants.addUndetected(cline.name)).pressKey(N)
                    .waitForText(M.source.addSource).pressKey(N),
            )
            const config = await readConfig(getDir())
            expect(config.assistants).toHaveLength(1)
            expect(config.assistants[0].id).toBe(cursor.id)
            expect(config.assistants[0].enabled).toBe(true)
        }, TIMEOUT_MS)

        it('excludes detected assistant when user declines keep', async () => {
            await mkdir(join(getDir(), '.cursor'), {recursive: true})

            await runInitSession(getDir(), (cli) =>
                cli
                    .waitForText(M.assistants.addUndetected(claudeCode.name)).pressKey(N)
                    .waitForText(M.assistants.keepDetected(cursor.name)).pressKey(N)
                    .waitForText(M.assistants.addUndetected(windsurf.name)).pressKey(N)
                    .waitForText(M.assistants.addUndetected(copilot.name)).pressKey(N)
                    .waitForText(M.assistants.addUndetected(cline.name)).pressKey(N)
                    .waitForText(M.source.addSource).pressKey(N),
            )
            const config = await readConfig(getDir())
            expect(config.assistants).toHaveLength(0)
        }, TIMEOUT_MS)

        it('detects assistant by file evidence (CLAUDE.md → claude-code keepDetected)', async () => {
            // Create detection file only — no directory — to exercise file-based detection path
            await Bun.write(join(getDir(), 'CLAUDE.md'), '# Claude instructions')

            await runInitSession(getDir(), (cli) =>
                cli
                    .waitForText(M.assistants.keepDetected(claudeCode.name)).pressKey(Y)
                    .waitForText(M.assistants.addUndetected(cursor.name)).pressKey(N)
                    .waitForText(M.assistants.addUndetected(windsurf.name)).pressKey(N)
                    .waitForText(M.assistants.addUndetected(copilot.name)).pressKey(N)
                    .waitForText(M.assistants.addUndetected(cline.name)).pressKey(N)
                    .waitForText(M.source.addSource).pressKey(N),
            )
            const config = await readConfig(getDir())
            expect(config.assistants).toHaveLength(1)
            expect(config.assistants[0].id).toBe(claudeCode.id)
            expect(config.assistants[0].enabled).toBe(true)
        }, TIMEOUT_MS)

        it('detects assistant by file evidence (copilot-instructions.md → copilot keepDetected)', async () => {
            await mkdir(join(getDir(), '.github'), {recursive: true})
            await Bun.write(join(getDir(), '.github', 'copilot-instructions.md'), '# Copilot instructions')

            await runInitSession(getDir(), (cli) =>
                cli
                    .waitForText(M.assistants.addUndetected(claudeCode.name)).pressKey(N)
                    .waitForText(M.assistants.addUndetected(cursor.name)).pressKey(N)
                    .waitForText(M.assistants.addUndetected(windsurf.name)).pressKey(N)
                    .waitForText(M.assistants.keepDetected(copilot.name)).pressKey(Y)
                    .waitForText(M.assistants.addUndetected(cline.name)).pressKey(N)
                    .waitForText(M.source.addSource).pressKey(N),
            )
            const config = await readConfig(getDir())
            expect(config.assistants).toHaveLength(1)
            expect(config.assistants[0].id).toBe(copilot.id)
            expect(config.assistants[0].enabled).toBe(true)
        }, TIMEOUT_MS)
    })
})
