import {readFile} from 'node:fs/promises'
import {join} from 'node:path'

import {useTmpDir} from '@test-helpers/tmp'
import {describe, expect, it} from 'bun:test'
import {parse as parseYaml} from 'yaml'

import {cursor} from '@domain/assistants/cursor'
import type {ProjectConfig} from '@domain/config/types'

import {CONFIG_HEADER, writeProjectConfig} from './writer'

const getDir = useTmpDir('config_writer')

const config: ProjectConfig = {
    version: '1',
    project: {name: 'test-project'},
    assistants: [{id: cursor.id, enabled: true}],
    source: {name: 'team', type: 'git', url: 'git@github.com:org/repo.git', branch: 'main'},
}

describe('writeProjectConfig', () => {
    it('returns the config file path', async () => {
        const configPath = await writeProjectConfig(getDir(), config)
        expect(configPath).toEndWith('.crucible/forge.config.yaml')
    })

    it('creates .crucible directory if it does not exist', async () => {
        await writeProjectConfig(getDir(), config)
        const {existsSync} = await import('node:fs')
        expect(existsSync(join(getDir(), '.crucible'))).toBe(true)
    })

    it('writes valid YAML that can be read back', async () => {
        const configPath = await writeProjectConfig(getDir(), config)
        const raw = await readFile(configPath, 'utf-8')
        const parsed = parseYaml(raw)
        expect(parsed.version).toBe('1')
        expect(parsed.assistants[0].id).toBe(cursor.id)
    })

    it('written file includes the forge config header comment', async () => {
        const configPath = await writeProjectConfig(getDir(), config)
        const raw = await readFile(configPath, 'utf-8')
        expect(raw).toContain(CONFIG_HEADER.split('\n')[0])
        expect(raw).toContain('Generated by forge init')
    })

    it('overwrites existing config file', async () => {
        const dir = getDir()
        await writeProjectConfig(dir, config)
        const updated: ProjectConfig = {...config, project: {name: 'updated-project'}}
        const configPath = await writeProjectConfig(dir, updated)
        const raw = await readFile(configPath, 'utf-8')
        const parsed = parseYaml(raw)
        expect(parsed.project.name).toBe('updated-project')
    })

    it('writes config with no source', async () => {
        const minimal: ProjectConfig = {version: '1', assistants: []}
        const configPath = await writeProjectConfig(getDir(), minimal)
        const raw = await readFile(configPath, 'utf-8')
        const parsed = parseYaml(raw)
        expect(parsed.source).toBeUndefined()
        expect(parsed.assistants).toEqual([])
    })
})
